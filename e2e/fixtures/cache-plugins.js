// The free page cache plugins Cache_Plugin_Purger clears, and Autoptimize. `on` and `off` are the WP-CLI calls that
// turn each one on and off through its own commands, options and functions. `working` tells from two loads of a page,
// a second or more apart, that the plugin worked on it: the second load came from its cache, or Autoptimize
// optimised it. WP Rocket is paid, so cache.spec.js covers it through llms-e2e-cache.php instead.

/**
 * The first match of a pattern's group in a body.
 *
 * @param {string} body    Body.
 * @param {RegExp} pattern Pattern with one group.
 * @return {string|undefined} Match.
 */
const stamp = ( body, pattern ) => ( body.match( pattern ) || [] )[ 1 ];

const CACHE_PLUGINS = [
	{
		slug: 'wp-super-cache',
		name: 'WP Super Cache',
		wordpressOrg: true,
		// Its mod_rewrite mode, where Apache serves the stored pages: in its PHP mode 3.1.4 never serves them, as
		// wp_cache_serve_cache_file() only does when $wp_cache_mfunc_enabled is unset and its config sets it to 0.
		on: [
			[ 'config', 'set', 'WP_CACHE', 'true', '--raw' ],
			[ 'plugin', 'activate', 'wp-super-cache' ],
			[ 'eval', "wp_cache_enable(); wp_cache_setting( 'wp_cache_mod_rewrite', 1 ); wpsc_update_htaccess();" ],
		],
		// Deactivating empties its rules and leaves WordPress's without RewriteEngine On, so those are written again.
		off: [ [ 'plugin', 'deactivate', 'wp-super-cache' ], [ 'config', 'delete', 'WP_CACHE' ], [ 'rewrite', 'flush', '--hard' ] ],
		// The stamp is the time the page was stored, to the second, so a served page keeps the first load's.
		working: ( first, second ) => {
			const made = stamp( first.body, /Cached page generated by WP-Super-Cache on ([\d-]+ [\d:]+)/ );
			return undefined !== made && made === stamp( second.body, /Cached page generated by WP-Super-Cache on ([\d-]+ [\d:]+)/ );
		},
	},
	{
		slug: 'w3-total-cache',
		name: 'W3 Total Cache',
		wordpressOrg: true,
		on: [
			[ 'plugin', 'activate', 'w3-total-cache' ],
			[ 'w3-total-cache', 'option', 'set', 'pgcache.enabled', 'true', '--type=boolean' ],
			[ 'w3-total-cache', 'fix_environment', 'apache' ],
		],
		off: [ [ 'plugin', 'deactivate', 'w3-total-cache' ], [ 'config', 'delete', 'WP_CACHE' ] ],
		// The footer is stamped to the second when the page is made, so a stored page keeps the first load's time.
		working: ( first, second ) => {
			const made = stamp( first.body, /Served from: .*? @ (.+?) by W3 Total Cache/ );
			return undefined !== made && made === stamp( second.body, /Served from: .*? @ (.+?) by W3 Total Cache/ );
		},
	},
	{
		slug: 'wp-fastest-cache',
		name: 'WP Fastest Cache',
		wordpressOrg: true,
		on: [ [ 'plugin', 'activate', 'wp-fastest-cache' ], [ 'option', 'update', 'WpFastestCache', '{"wpFastestCacheStatus":"on"}' ] ],
		// The option goes first: with it set, activating the plugin again would write its .htaccess rules.
		off: [ [ 'option', 'delete', 'WpFastestCache' ], [ 'plugin', 'deactivate', 'wp-fastest-cache' ] ],
		working: ( first, second ) => second.body.includes( '<!-- via php -->' ),
	},
	{
		slug: 'autoptimize',
		name: 'Autoptimize',
		wordpressOrg: true,
		on: [
			[ 'plugin', 'activate', 'autoptimize' ],
			[ 'option', 'update', 'autoptimize_html', 'on' ],
			[ 'option', 'update', 'autoptimize_js', 'on' ],
			// Aggregated scripts, inline ones included, go into a file under /cache/autoptimize/.
			[ 'option', 'update', 'autoptimize_js_aggregate', 'on' ],
			[ 'option', 'update', 'autoptimize_js_include_inline', 'on' ],
			[ 'option', 'update', 'autoptimize_css', 'on' ],
		],
		off: [
			[ 'plugin', 'deactivate', 'autoptimize' ],
			[ 'option', 'delete', 'autoptimize_html', 'autoptimize_js', 'autoptimize_js_aggregate', 'autoptimize_js_include_inline', 'autoptimize_css' ],
		],
		working: ( first, second ) => second.body.includes( '/cache/autoptimize/' ),
	},
];

module.exports = { CACHE_PLUGINS };
